    /** 返回 {大类, 小类}。 */
    public static String[] classify(int type, String platformCategory,
                                    String counterparty, String product) {
        String hay = (nz(platformCategory) + " " + nz(counterparty) + " " + nz(product));
        String[][] table = type == Entry.INCOME ? INCOME : EXPENSE;
        for (String[] rule : table) {
            if (hay.contains(rule[0])) {
                return new String[]{rule[1], rule[2]};
            }
        }
        return type == Entry.INCOME
                ? new String[]{"其他收入", "其他收入"}
                : new String[]{"人情与金融", "其他支出"};
    }

    private static String nz(String s) {
        return s == null ? "" : s;
    }
